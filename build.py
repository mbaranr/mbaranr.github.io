#!/usr/bin/env python3
"""Rebuild the post lists and feed.xml from the posts in blog/*/index.html.

Each post is the source of truth for its own entry:
  title    the first <h1>
  date     <p class="meta"><i><time datetime="YYYY-MM-DD">
  summary  <meta name="description" content="...">

Run it after adding or editing a post:

    python3 build.py

It rewrites the lists between the <!-- posts --> markers in blog/index.html
(every post) and index.html (the newest few), and regenerates feed.xml.
Running it twice changes nothing. Python 3 standard library only.
"""

import html
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent
SITE = "https://mbaranr.github.io"
RECENT = 5  # posts shown on the homepage
MONTHS = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()

H1 = re.compile(r"<h1>(.*?)</h1>", re.S)
DATE = re.compile(r'<p class="meta"><i><time datetime="(\d{4})-(\d{2})-(\d{2})">')
DESC = re.compile(r'<meta name="description" content="(.*?)">')
OG_URL = re.compile(r'<meta property="og:url" content="(.*?)">')
MARKERS = re.compile(r"(<!-- posts:start -->\n).*?(<!-- posts:end -->)", re.S)


def read_posts():
    posts, problems = [], []
    for page in sorted(ROOT.glob("blog/*/index.html")):
        slug = page.parent.name
        text = page.read_text(encoding="utf-8")
        h1, date, desc = H1.search(text), DATE.search(text), DESC.search(text)
        missing = [n for n, m in (("<h1>", h1), ('<p class="meta"> date', date),
                                  ("description <meta>", desc)) if not m]
        if missing:
            problems.append(f"blog/{slug}/index.html: missing {', '.join(missing)}")
            continue
        url = f"{SITE}/blog/{slug}/"
        og = OG_URL.search(text)
        if not og or og.group(1) != url:
            print(f"warning: blog/{slug}/index.html: og:url should be {url}", file=sys.stderr)
        y, m, d = date.groups()
        posts.append({
            "slug": slug,
            "title": h1.group(1).strip(),
            "date": f"{y}-{m}-{d}",
            "pretty": f"{d} {MONTHS[int(m) - 1]}, {y}",
            "summary": desc.group(1),
        })
    if problems:
        sys.exit("error:\n  " + "\n  ".join(problems))
    # Newest first; posts on the same day in folder-name order.
    posts.sort(key=lambda p: p["slug"])
    posts.sort(key=lambda p: p["date"], reverse=True)
    return posts


def list_items(posts):
    return "".join(
        f'<li><span class="date"><i><time datetime="{p["date"]}">{p["pretty"]}</time></i></span>'
        f'<a href="/blog/{p["slug"]}/">{p["title"]}</a></li>\n'
        for p in posts
    )


def fill_list(path, posts):
    text = path.read_text(encoding="utf-8")
    if not MARKERS.search(text):
        sys.exit(f"error: {path.name} has no <!-- posts:start --> / <!-- posts:end --> markers")
    new = MARKERS.sub(lambda m: m.group(1) + list_items(posts) + m.group(2), text, count=1)
    return write(path, new)


def xml_text(fragment):
    """HTML fragment -> plain text safe inside an XML element."""
    return escape(html.unescape(re.sub(r"<[^>]+>", "", fragment)))


def build_feed(posts):
    newest = posts[0]["date"] if posts else "1970-01-01"
    entries = "".join(f"""  <entry>
    <title>{xml_text(p["title"])}</title>
    <link href="{SITE}/blog/{p["slug"]}/"/>
    <id>{SITE}/blog/{p["slug"]}/</id>
    <published>{p["date"]}T00:00:00Z</published>
    <updated>{p["date"]}T00:00:00Z</updated>
    <summary>{xml_text(p["summary"])}</summary>
  </entry>
""" for p in posts)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by build.py from blog/*/index.html. Don't edit by hand. -->
<feed xmlns="http://www.w3.org/2005/Atom">
  <title>Matias Barandiaran</title>
  <subtitle>Posts by Matias Barandiaran, quantitative developer in Leipzig.</subtitle>
  <link href="{SITE}/feed.xml" rel="self"/>
  <link href="{SITE}/"/>
  <id>{SITE}/</id>
  <updated>{newest}T00:00:00Z</updated>
  <author><name>Matias Barandiaran</name><email>mbarandiaranr@gmail.com</email></author>
{entries}</feed>
"""


def write(path, text):
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8")
    return True


def main():
    posts = read_posts()
    changed = [
        name for name, did in (
            ("blog/index.html", fill_list(ROOT / "blog/index.html", posts)),
            ("index.html", fill_list(ROOT / "index.html", posts[:RECENT])),
            ("feed.xml", write(ROOT / "feed.xml", build_feed(posts))),
        ) if did
    ]
    print(f"{len(posts)} posts. " + (f"Updated {', '.join(changed)}." if changed else "Nothing to change."))


if __name__ == "__main__":
    main()
